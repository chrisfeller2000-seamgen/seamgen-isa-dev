#!/usr/bin/env node
// Rebuilds the skill table in workspace/skills/rfp/INDEX.md from each skill's header
// (skills/rfp/<skill>/instructions.md), so a skill's trigger and phase are edited in one place.
//
//   npm run rfp:index           rewrites the table
//   npm run rfp:index -- --check  exits 1 if the table is out of date (the tests do the same)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSkills } from '../workspace/scripts/rfp-route.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const INDEX_PATH = path.join(repoRoot, 'workspace', 'skills', 'rfp', 'INDEX.md');
const START = '<!-- skill-table:start (generated by npm run rfp:index; edit the skill headers instead) -->';
const END = '<!-- skill-table:end -->';

export function renderSkillTable(skills) {
  const phase = skill => (skill.phase ? String(skill.phase) : 'any');
  const order = [...skills].sort((a, b) => (a.phase || 9) - (b.phase || 9) || a.label.localeCompare(b.label));
  return [START,
    '| Skill | When someone asks for | Phase | Command | File |',
    '| --- | --- | --- | --- | --- |',
    ...order.map(skill => `| ${skill.label} | ${skill.when.replace(/\|/g, '/')} | ${phase(skill)} | \`rfp ${skill.command} <rfp>\` | \`${skill.file}\` |`),
    END].join('\n');
}

/** The INDEX.md text with the table replaced by one built from the current skill headers. */
export async function rebuiltIndex() {
  const text = await fs.readFile(INDEX_PATH, 'utf8');
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start < 0 || end < start) throw new Error('INDEX.md has no skill-table markers.');
  const skills = await loadSkills({ workspace: path.join(repoRoot, 'workspace') });
  return `${text.slice(0, start)}${renderSkillTable(skills)}${text.slice(end + END.length)}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = await rebuiltIndex();
  const current = await fs.readFile(INDEX_PATH, 'utf8');
  if (process.argv.includes('--check')) {
    if (next !== current) {
      process.stderr.write('The skill table in INDEX.md is out of date. Run: npm run rfp:index\n');
      process.exitCode = 1;
    }
  } else if (next !== current) {
    await fs.writeFile(INDEX_PATH, next);
    process.stdout.write('Rebuilt the skill table in INDEX.md.\n');
  } else {
    process.stdout.write('INDEX.md is already up to date.\n');
  }
}
