// The weekly RFP results, the Friday Telegram message, and the email.
// Code decides every fact here: tiers, scores, deadlines, budgets, links and counts.
// ISA's model only words the Telegram message, and its draft is sent only when it
// matches those facts; otherwise the code-built version below is sent.
import { deadlineTimestamp } from './rfp-deadline.mjs';

const PACIFIC = 'America/Los_Angeles';
const MIN_PICK_SCORE = 50;
const STRONG_PURSUE = 75;
const MINIMUM_DEAL = 100000;
// A screened-out RFP this large, skipped for a reason a partner could cover, is named in the
// message so someone can overrule it. Peter asked that product-shaped RFPs be treated as a
// teaming question rather than an automatic No-bid (Jake's feedback log, July 26).
const SKIPPED_MIN_VALUE = 500000;
const PARTNER_GATES = new Set(['gate2', 'gate6']);
const MAX_PICKS = 3;
const MAX_MESSAGE_CHARS = 3000;
const GATE_KEYS = ['gate1', 'gate2', 'gate3', 'gate4', 'gate5', 'gate6'];
// Eligibility is usually the real blocker, so it is asked first. An unconfirmed deadline
// is stated in the due line rather than asked.
const QUESTION_GATES = ['gate6', 'gate2', 'gate5', 'gate4', 'gate3'];
const DEFAULT_VIBE = 'Warm, direct, commercially sharp';
const EMAIL_FOOTER = 'This email is generated by ISA, the AI assistant of Seamgen. ISA has been fed and trained with relevant knowledge, and the content and expressions are supervised. For personal contact, you can always call or email me.';

// Plain words for each screened-out reason: `one`/`many` finish "1 …"/"52 …",
// `noun` finishes "Most were …", and `heading` labels the email group.
const REASONS = {
  gate1: { one: 'is due too soon or closed', many: 'are due too soon or closed', noun: 'due too soon', heading: 'Due too soon or closed' },
  gate2: { one: 'is buying an existing product', many: 'are buying existing products', noun: 'existing products', heading: 'Buying an existing product' },
  gate3: { one: 'is hardware or equipment', many: 'are hardware or equipment', noun: 'hardware', heading: 'Hardware or equipment' },
  gate4: { one: "can't be submitted", many: "can't be submitted", noun: 'not possible to submit', heading: "Can't be submitted" },
  gate5: { one: 'is under $100k', many: 'are under $100k', noun: 'under $100k', heading: 'Under $100k' },
  gate6: { one: "needs eligibility we can't meet", many: "need eligibility we can't meet", noun: 'outside our eligibility', heading: "Eligibility we can't meet" },
  weak: { one: 'is a weak fit', many: 'are weak fits', noun: 'weak fits', heading: 'Weak fit (score under 50)' },
  notOpen: { one: "isn't an open bid", many: "aren't open bids", noun: 'not open bids', heading: 'Not an open bid' },
  watch: { one: 'is an early notice', many: 'are early notices', noun: 'early notices', heading: 'Early notice (pre-solicitation)' },
  thin: { one: 'had too little detail to judge', many: 'had too little detail to judge', noun: 'too thin to judge', heading: 'Too little listing detail' },
  hubspot: { one: 'is already in HubSpot', many: 'are already in HubSpot', noun: 'already in HubSpot', heading: 'Already in HubSpot' },
};
const CHECK_REASONS = {
  documents: "couldn't get or read the RFP documents",
  disabled: 'document fetching is turned off',
  unscored: "the AI scoring didn't finish",
  noDeadline: "the listing has no deadline, so it wasn't scored",
  agency: 'needs an answer from the agency before it can be scored',
};
const TIER_ORDER = { strong: 0, worth: 1, check: 2, screened: 3 };

const clean = value => String(value ?? '').replace(/\s+/g, ' ').trim();
const finite = value => (Number.isFinite(value) ? value : null);
const plural = (count, one, many) => (count === 1 ? one : many);

function firstSentence(text, max = 260) {
  const value = clean(text);
  if (!value) return '';
  const sentence = (value.match(/^.*?[.!?](?=\s|$)/) || [value])[0];
  if (sentence.length <= max) return sentence;
  return `${sentence.slice(0, max).replace(/\s+\S*$/, '')}…`;
}

function publicUrl(value) {
  const url = clean(value);
  return /^https?:\/\//i.test(url) ? url : '';
}

function money(amount, withSign = true) {
  const text = amount >= 1e6 ? `${+(amount / 1e6).toFixed(1)}M` : amount >= 1e3 ? `${Math.round(amount / 1e3)}k` : `${amount}`;
  return `${withSign ? '$' : ''}${text}`;
}

function budgetOf(value = {}) {
  const status = value?.status || 'unstated';
  const low = finite(value?.low ?? (status === 'stated' ? value?.estimate : null));
  const high = finite(value?.high ?? (status === 'stated' ? value?.estimate : null));
  if (status === 'conflicting') return { low: null, high: null, text: 'unclear (the sources disagree)' };
  if (low === null && high === null) return { low: null, high: null, text: 'not listed' };
  const amount = status === 'ceiling' ? `up to ${money(high)}`
    : low !== null && high !== null && low !== high ? `${money(low)}–${money(high, false)}`
      : low !== null && high === null ? `${money(low)}+` : money(high ?? low);
  return status === 'listing'
    ? { low, high, text: `about ${amount} (HigherGov's guess)` }
    : { low, high, text: `${amount} (from the RFP)` };
}

function formatDay(iso, timeZone) {
  return new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric', timeZone }).format(new Date(iso));
}

function formatTime(iso, timeZone) {
  return new Intl.DateTimeFormat('en-US', { hour: 'numeric', minute: '2-digit', timeZone }).format(new Date(iso))
    .replace(':00', '').replace(/\s?([AP])M$/, (_, half) => `${half.toLowerCase()}m`);
}

// Pacific time for the team, from the cutoff the deadline module verified.
function deadlineOf(timeline = {}) {
  const date = timeline?.due || null;
  if (!date) return { date: null, confirmed: false, days: null, text: 'no deadline found' };
  const confirmed = timeline.status === 'verified';
  const days = finite(timeline.days);
  if (!confirmed) return { date, confirmed, days, text: `the listing says ${formatDay(`${date}T12:00:00Z`, 'UTC')}` };
  const cutoff = deadlineTimestamp(date, timeline.time, timeline.timeZone);
  const when = cutoff ? `${formatDay(cutoff, PACIFIC)} at ${formatTime(cutoff, PACIFIC)} PT` : formatDay(`${date}T12:00:00Z`, 'UTC');
  const left = days === null ? '' : days === 0 ? ' (today)' : ` (${days} ${plural(days, 'day', 'days')})`;
  return { date, confirmed, days, text: `${when}${left}` };
}

// HigherGov's own summary, without its "Background" heading.
function needOf(candidate = {}) {
  const section = (String(candidate.body || '').match(/## HigherGov AI summary\s+([\s\S]*?)(?:\n## |$)/) || [])[1];
  const text = clean(section || candidate.frontmatter?.ai_summary || candidate.frontmatter?.description_text)
    .replace(/^(background|summary|overview|purpose)\b[\s:.\-–]*/i, '');
  return firstSentence(text, 200);
}

// The scorer sometimes opens a reason with rubric shorthand ("FAIL —", "Eligibility needs
// verification:"); the team sees only the plain sentence after it.
const RUBRIC_PREFIX = /^(?:(?:fail|pass|unknown)\s*[—–:-]\s*|(?:eligibility|deadline) needs (?:verification|review):\s*)/i;

function gateReason(result, key) {
  const reason = result?.gateReasons?.find(item => item.gate === `Gate ${key.slice(4)}`)?.reason;
  if (reason) return firstSentence(clean(reason).replace(RUBRIC_PREFIX, '').replace(/^\w/, letter => letter.toUpperCase()));
  if (key === 'gate1') return firstSentence(result?.timeline?.note);
  if (key === 'gate5') return firstSentence(result?.value?.reason);
  return '';
}

function failedGate(result) {
  const key = GATE_KEYS.find(name => result?.gate?.[name] === false);
  return key ? { key, detail: gateReason(result, key) } : null;
}

function openQuestions(final) {
  if (!final?.gate) return [];
  const conditional = final.recommendation === 'Conditional — Ask the Agency';
  return QUESTION_GATES.filter(key => final.gate[key] === null && !(conditional && key === 'gate2'))
    .map(key => gateReason(final, key)).filter(Boolean).slice(0, 2);
}

function rankOf(final, preliminary) {
  if (Number.isFinite(final?.total)) return { score: final.total, from: 'final' };
  if (Number.isFinite(final?.potential_total)) return { score: final.potential_total, from: 'potential' };
  if (Number.isFinite(preliminary?.total)) return { score: preliminary.total, from: 'preliminary' };
  return { score: null, from: null };
}

function placement({ preliminary, final, documentStatus, hubspotDuplicate }) {
  const prelim = preliminary?.preview || {};
  const screened = (key, detail = '') => ({ tier: 'screened', reason: key, detail });
  const check = key => ({ tier: 'check', reason: key, detail: '' });
  if (preliminary?.status === 'insufficient-metadata') return screened('thin');
  const result = final || prelim;
  // A gate the code decided (deadline, value) stays a No-bid even if the AI call failed.
  const failed = failedGate(result);
  if (failed) return screened(failed.key, failed.detail);
  if (result.recommendation === 'Not an open bid') return screened('notOpen');
  if (result.recommendation === 'Watch item') return screened('watch');
  if (result.scoring_error) return check('unscored');
  if (!final) {
    if (prelim.recommendation === 'Conditional — Ask the Agency') return check('agency');
    if (prelim.recommendation === 'Deadline needs review') return check('noDeadline');
    if (!Number.isFinite(prelim.total)) return check('unscored');
    if (prelim.total < MIN_PICK_SCORE) return screened('weak');
    return check(documentStatus === 'fetch-disabled' ? 'disabled' : 'documents');
  }
  if (final.recommendation === 'Needs documents') return check('documents');
  if (hubspotDuplicate) return screened('hubspot');
  if (final.recommendation === 'Strong Pursue') return { tier: 'strong', reason: null, detail: '' };
  const rank = rankOf(final, prelim).score;
  return rank !== null && rank >= MIN_PICK_SCORE ? { tier: 'worth', reason: null, detail: '' } : screened('weak');
}

/**
 * One results-file entry per RFP. `preliminary` is the weekly job's preliminary result
 * ({ status, preview }); `final` is the full-text result when documents were scored.
 */
export function reportEntry({ candidate, preliminary, final = null, documentStatus = 'metadata-only', hubspotDuplicate = false, documentsLink = '' }) {
  const frontmatter = candidate?.frontmatter || {};
  const prelim = preliminary?.preview || {};
  const result = final || prelim;
  const place = placement({ preliminary, final, documentStatus, hubspotDuplicate });
  const rank = rankOf(final, prelim);
  const questions = place.tier === 'worth' || place.tier === 'strong' ? openQuestions(final) : [];
  const budget = budgetOf(result.value);
  const listing = publicUrl(candidate?.sourceUrl || frontmatter.source_url);
  const posting = publicUrl(candidate?.portalUrl || frontmatter.solicitation_url);
  const conditional = final?.recommendation === 'Conditional — Ask the Agency' ? firstSentence(final.conditional?.question) : '';
  return {
    slug: candidate?.slug || '',
    title: clean(candidate?.title || frontmatter.title || candidate?.slug),
    agency: clean(candidate?.issuer || frontmatter.agency_name),
    state: /^[A-Z]{2}$/.test(clean(frontmatter.pop_state)) ? clean(frontmatter.pop_state) : '',
    links: { highergov: listing, posting: posting !== listing ? posting : '', documents: publicUrl(documentsLink) },
    tier: place.tier,
    reason: place.reason,
    reasonDetail: place.detail,
    recommendation: result.recommendation || null,
    scoredFrom: final ? 'documents' : 'listing',
    score: finite(result.total),
    rankScore: rank.score,
    rankFrom: rank.from,
    scoreIfYes: questions.length ? finite(final?.potential_total) : null,
    need: needOf(candidate),
    fit: firstSentence(result.judgments?.categories?.caseStudy?.reason) || null,
    questions,
    agencyQuestion: conditional || null,
    notes: (result.flags || []).map(flag => firstSentence(flag.reason)).filter(Boolean).slice(0, 2),
    deadline: deadlineOf(result.timeline),
    budget,
    longShot: place.tier === 'worth' && (rank.from === 'preliminary' || questions.length >= 2 || (budget.low !== null && budget.low < MINIMUM_DEAL)),
  };
}

/** The results file: every entry, sorted by tier and then rank score, plus the week's counts. */
export function buildResults({ runDate, week, entries, intake = {} }) {
  const sorted = [...entries].sort((a, b) => TIER_ORDER[a.tier] - TIER_ORDER[b.tier]
    || (b.rankScore ?? -1) - (a.rankScore ?? -1) || a.title.localeCompare(b.title));
  const counts = Object.fromEntries(Object.keys(TIER_ORDER).map(tier => [tier, entries.filter(entry => entry.tier === tier).length]));
  return { runDate, week, total: entries.length, counts,
    intake: { fetched: intake.fetched ?? null, passed: intake.pass ?? null, days: intake.daysFetched?.length ?? null }, entries: sorted };
}

function biggestSkipped(screened) {
  return screened.filter(entry => PARTNER_GATES.has(entry.reason) && (entry.budget.high ?? entry.budget.low ?? 0) >= SKIPPED_MIN_VALUE)
    .sort((a, b) => (b.budget.high ?? b.budget.low) - (a.budget.high ?? a.budget.low))[0] || null;
}

function reasonCounts(entries) {
  const counts = new Map();
  for (const entry of entries) counts.set(entry.reason, (counts.get(entry.reason) || 0) + 1);
  return [...counts].sort((a, b) => b[1] - a[1]).map(([key, count]) => ({
    count, text: count === 1 ? REASONS[key].one : REASONS[key].many, noun: REASONS[key].noun }));
}

/** Everything the Telegram message may say, and nothing else. */
export function telegramFacts(results, { emailOwner = 'Marianne' } = {}) {
  const ranked = results.entries.filter(entry => entry.tier === 'strong' || entry.tier === 'worth');
  const picks = ranked.slice(0, MAX_PICKS);
  const check = results.entries.filter(entry => entry.tier === 'check');
  const screened = results.entries.filter(entry => entry.tier === 'screened');
  const skipped = biggestSkipped(screened);
  const notAFit = screened.filter(entry => entry !== skipped);
  return {
    total: results.total,
    verdict: {
      strong: picks.filter(pick => pick.tier === 'strong').length,
      worth: picks.filter(pick => pick.tier === 'worth' && !pick.longShot).length,
      longShots: picks.filter(pick => pick.longShot).length,
    },
    picks: picks.map((entry, index) => ({
      number: index + 1,
      title: entry.title,
      agency: entry.agency,
      need: entry.need,
      fit: entry.fit,
      questions: entry.questions,
      agencyQuestion: entry.agencyQuestion,
      score: entry.rankFrom === 'final' ? entry.score : null,
      scoreIfYes: entry.scoreIfYes,
      strongPursue: entry.tier === 'strong',
      longShot: entry.longShot,
      longShotReasons: entry.longShot ? [
        entry.rankFrom === 'preliminary' ? "the deadline isn't confirmed, so it only has its listing score" : null,
        entry.questions.length >= 2 ? 'it has two open questions' : null,
        entry.budget.low !== null && entry.budget.low < MINIMUM_DEAL ? 'the budget may be under our $100k minimum' : null,
      ].filter(Boolean) : [],
      deadline: { confirmed: entry.deadline.confirmed, date: entry.deadline.date, text: entry.deadline.text },
      budget: entry.budget.text,
      link: entry.links.highergov,
    })),
    morePicks: ranked.length - picks.length,
    skipped: skipped ? { title: skipped.title, agency: skipped.agency, budget: skipped.budget.text,
      reason: REASONS[skipped.reason].one, why: skipped.reasonDetail } : null,
    check: { count: check.length, allDocuments: check.every(entry => entry.reason === 'documents') },
    notAFit: { count: notAFit.length, reasons: reasonCounts(notAFit) },
    emailOwner,
  };
}

function listJoin(items) {
  if (items.length <= 1) return items.join('');
  if (items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0, -1).join(', ')}, and ${items.at(-1)}`;
}

function verdictText({ strong, worth, longShots }) {
  const parts = [];
  if (strong) parts.push(`${strong} ${plural(strong, 'is a strong pursue', 'are strong pursues')}`);
  if (worth) parts.push(`${worth} ${plural(worth, 'is', 'are')} worth a look`);
  const shots = plural(longShots, 'a long shot', `${longShots} long shots`);
  if (!parts.length) return longShots === 1 ? "Nothing solid, but there's a long shot." : `Nothing solid, but there are ${shots}.`;
  return `${parts.join(' and ')}${longShots ? `, plus ${shots}` : ''}.`;
}

function scoreText(score) {
  return `${score}${score >= STRONG_PURSUE ? ', a strong pursue' : ''}`;
}

function questionLine(pick) {
  if (pick.agencyQuestion) return `Question for the agency: ${pick.agencyQuestion}${pick.scoreIfYes !== null ? ` If the answer works for us, it scores ${scoreText(pick.scoreIfYes)}.` : ''}`;
  if (pick.questions.length) {
    const several = pick.questions.length > 1;
    return `${several ? 'Questions' : 'Question'} for the team: can we meet ${several ? 'these' : 'this'}? ${pick.questions.join(' ')}`
      + (pick.scoreIfYes !== null ? ` If yes, it scores ${scoreText(pick.scoreIfYes)}.` : '');
  }
  return pick.score !== null ? `It scores ${scoreText(pick.score)}.` : null;
}

function dueLine(pick) {
  const due = pick.deadline.confirmed ? `Due ${pick.deadline.text}.`
    : pick.deadline.date ? `I couldn't confirm the deadline (${pick.deadline.text}).` : 'No deadline found.';
  return `${due} Budget ${pick.budget}.`;
}

function documentsLine(facts) {
  const { count, allDocuments } = facts.check;
  if (!count) return '';
  const where = facts.picks.length ? `in ${facts.emailOwner}'s email` : `at the top of ${facts.emailOwner}'s email`;
  const it = plural(count, "It's", "They're");
  return allDocuments
    ? `${count} looked promising, but I couldn't get ${plural(count, 'its', 'their')} documents to check the requirements. ${it} ${where}.`
    : `${count} I couldn't finish checking. ${it} ${where}.`;
}

function notAFitLine(facts) {
  const { count, reasons } = facts.notAFit;
  const full = `Full list is in ${facts.emailOwner}'s email.`;
  if (!count) return full;
  if (count === 1) return `The other one ${reasons[0].text}. ${full}`;
  const shown = reasons.slice(0, 3).map(reason => `${reason.count} ${reason.text}`);
  const rest = reasons.slice(3).reduce((sum, reason) => sum + reason.count, 0);
  if (rest) shown.push(`${rest} for other reasons`);
  return `The other ${count} weren't a fit: ${listJoin(shown)}. ${full}`;
}

function skippedLine(skipped) {
  return `Biggest one I skipped: ${skipped.title}${skipped.agency ? `, ${skipped.agency}` : ''}, ${skipped.budget}. ${skipped.why || `It ${skipped.reason}.`} It's only worth it with a partner.`;
}

/** The code-built message: sent when ISA's draft fails a check or the writer fails. */
export function renderTelegramFallback(facts) {
  if (!facts.picks.length) {
    const top = facts.notAFit.reasons.slice(0, 2).map(reason => reason.noun);
    const body = [`I went through ${facts.total} ${plural(facts.total, 'RFP', 'RFPs')}.`, top.length ? `Most were ${top.join(' or ')}.` : '', documentsLine(facts)]
      .filter(Boolean).join(' ');
    return ['Morning team. Nothing worth chasing this week.', body, facts.skipped ? skippedLine(facts.skipped) : '']
      .filter(Boolean).join('\n\n');
  }
  const blocks = facts.picks.map(pick => [
    `${pick.number}. ${pick.longShot ? 'Long shot: ' : ''}**${pick.title}${pick.agency ? `, ${pick.agency}` : ''}**`,
    pick.need,
    pick.fit ? `Why us: ${pick.fit}` : '',
    questionLine(pick),
    dueLine(pick),
    pick.link ? `[HigherGov listing](${pick.link})` : '',
  ].filter(Boolean).join('\n'));
  const more = facts.morePicks ? `${facts.morePicks} more ${plural(facts.morePicks, 'is', 'are')} worth a look in ${facts.emailOwner}'s email.` : '';
  return [
    `Morning team! I went through ${facts.total} new RFPs this week. ${verdictText(facts.verdict)}`,
    ...blocks,
    facts.skipped ? skippedLine(facts.skipped) : '',
    [documentsLine(facts), more, notAFitLine(facts)].filter(Boolean).join('\n'),
  ].filter(Boolean).join('\n\n');
}

const NUMBER_WORDS = { one: 1, two: 2, three: 3, four: 4, five: 5, six: 6, seven: 7, eight: 8, nine: 9, ten: 10,
  eleven: 11, twelve: 12, fifteen: 15, twenty: 20, thirty: 30 };
const numbersIn = text => new Set((String(text).match(/\d+(?:\.\d+)?/g) || []).map(Number));
const linksIn = text => [...String(text).matchAll(/https?:\/\/[^\s)\]>]+/g)].map(match => match[0]);
const FORBIDDEN = [
  [/\/(?:home|tmp|Users|var)\//, 'a file path'],
  [/\bgates?\s*\d/i, 'a gate number'],
  [/\b[a-z][a-z-]*:e\d+\b/, 'an excerpt ID'],
  [/\b(?:metadata-only|full-text|failed-gate|preliminary-below-threshold|access-blocked|partial-documents|insufficient-metadata)\b/i, 'an internal code'],
  [/\p{Extended_Pictographic}/u, 'an emoji'],
];

/** Compares ISA's draft with the facts. Returns { ok, reason }. */
export function checkTelegramDraft(draft, facts) {
  const text = String(draft || '').trim();
  const fail = reason => ({ ok: false, reason });
  if (!text) return fail('The draft was empty.');
  if (text.length > MAX_MESSAGE_CHARS) return fail(`The draft was over ${MAX_MESSAGE_CHARS} characters.`);
  for (const [pattern, what] of FORBIDDEN) if (pattern.test(text)) return fail(`The draft contained ${what}.`);
  // Only bold and links are allowed. RFP titles can contain "#" or "|", so only real
  // Markdown structures are rejected: headings, tables, bullets, code, and italics.
  const plain = text.replace(/\*\*([^*\n]+)\*\*/g, '$1').replace(/\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)/g, '$1');
  if (/[*`]/.test(plain) || /^\s*#{1,6}\s/m.test(plain) || /^\s*\|.*\|\s*$/m.test(plain) || /^\s*[-•]\s/m.test(plain)
    || /(^|\s)_[^_\n]+_(?=[\s.,!?]|$)/.test(plain)) return fail('The draft used formatting other than bold and links.');

  const expected = facts.picks.map(pick => pick.link).filter(Boolean);
  const links = linksIn(text);
  if (links.length !== expected.length || links.some((link, index) => link !== expected[index])) {
    return fail('The draft links did not match the picks, in order.');
  }

  // Every number must come from the facts (including numbers spelled out there), and the
  // key numbers must be present.
  const factsText = JSON.stringify(facts);
  const allowed = numbersIn(factsText);
  for (const [word, value] of Object.entries(NUMBER_WORDS)) if (new RegExp(`\\b${word}\\b`, 'i').test(factsText)) allowed.add(value);
  facts.picks.forEach(pick => allowed.add(pick.number));
  const used = numbersIn(text.replace(/https?:\/\/[^\s)\]>]+/g, ''));
  const stray = [...used].find(value => !allowed.has(value));
  if (stray !== undefined) return fail(`The draft contained a number that is not in the facts (${stray}).`);
  const required = [facts.total];
  if (facts.picks.length && facts.notAFit.count > 1) required.push(facts.notAFit.count);
  for (const pick of facts.picks) {
    if (pick.score !== null) required.push(pick.score);
    if (pick.scoreIfYes !== null) required.push(pick.scoreIfYes);
    if (pick.deadline.confirmed) required.push(...numbersIn(pick.deadline.text));
    if (!/not listed|unclear/.test(pick.budget)) required.push(...numbersIn(pick.budget));
  }
  const missing = required.find(value => !used.has(value));
  if (missing !== undefined) return fail(`The draft left out a number from the facts (${missing}).`);

  if (/long shot/i.test(text) && !facts.picks.some(pick => pick.longShot)) return fail('The draft called a pick a long shot without the flag.');
  if (/\bskipp?(?:ed|ing)?\b/i.test(text) !== Boolean(facts.skipped)) return fail('The draft did not match the skipped-RFP fact.');
  return { ok: true, reason: null };
}

